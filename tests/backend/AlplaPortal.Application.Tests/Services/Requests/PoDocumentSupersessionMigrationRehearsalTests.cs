/// <summary>
/// v2.249.4 — the REAL migration <c>20261029140552_AddPoDocumentSupersessionAndExtraction</c> rehearsed against a database that
/// is at the PREVIOUS migration with PRE-MIGRATION rows (not a database recreated from the current model):
///  • the Up operations are exactly the intended additive schema (4 nullable columns, 1 table, 1 index) — nothing else;
///  • a legacy group with TWO live P.O. files and no pointer survives the migration unchanged (new columns NULL) and the reader
///    rule picks the newest live file of THAT group only;
///  • a voided legacy file is never current; a cancelled legacy group has no current document.
/// Runs on the LocalDB used by the other relational tests, in its own disposable database; skips silently when LocalDB is
/// unavailable (repository convention).
/// </summary>
[Collection("IntegrationTests")]
public class PoDocumentSupersessionMigrationRehearsalTests
{
    private const string PreviousMigration = "20261028082044_AddPoGroupCancellation";
    private const string TargetMigration = "20261029140552_AddPoDocumentSupersessionAndExtraction";

    private static string RehearsalConnectionString()
    {
        var b = new SqlConnectionStringBuilder(IntegrationTestDatabaseAccessor.ConnectionString()) { InitialCatalog = "Portal-Gerencial-MigrationRehearsal-v2249-4" };
        return b.ConnectionString;
    }

    private static ApplicationDbContext NewCtx() => new(new DbContextOptionsBuilder<ApplicationDbContext>().UseSqlServer(RehearsalConnectionString()).Options);

    [Fact]
    public void The_migration_contains_only_the_intended_additive_operations()
    {
        var ops = new AddPoDocumentSupersessionAndExtraction().UpOperations;
        var addColumns = ops.OfType<AddColumnOperation>().ToList();
        Assert.Equal(4, addColumns.Count);
        Assert.All(addColumns, c => Assert.True(c.IsNullable, c.Name + " must be nullable"));
        Assert.Contains(addColumns, c => c.Table == "RequestPoGroups" && c.Name == "CurrentPoAttachmentId");
        Assert.Contains(addColumns, c => c.Table == "RequestAttachments" && c.Name == "SupersededAtUtc");
        Assert.Contains(addColumns, c => c.Table == "RequestAttachments" && c.Name == "SupersededByAttachmentId");
        Assert.Contains(addColumns, c => c.Table == "RequestAttachments" && c.Name == "SupersededByUserId");
        var table = Assert.Single(ops.OfType<CreateTableOperation>());
        Assert.Equal("PoDocumentExtractions", table.Name);
        var index = Assert.Single(ops.OfType<CreateIndexOperation>());
        Assert.Equal("IX_PoDocumentExtractions_Request_Hash_Created", index.Name);
        Assert.Equal(6, ops.Count);                                   // nothing else: no drop, no alter, no data, no FK change
        Assert.Empty(ops.OfType<SqlOperation>()); Assert.Empty(ops.OfType<DropColumnOperation>()); Assert.Empty(ops.OfType<AlterColumnOperation>()); Assert.Empty(ops.OfType<InsertDataOperation>()); Assert.Empty(ops.OfType<UpdateDataOperation>());
    }

    [Fact]
    public async Task Applying_the_migration_to_a_pre_migration_database_keeps_legacy_PO_files_and_the_reader_picks_the_newest_live_file_per_group()
    {
        if (!IntegrationTestDatabaseAccessor.CanConnect()) return;   // LocalDB unavailable: skip (repo convention)
        await using var ctx = NewCtx();
        await ctx.Database.EnsureDeletedAsync();

        // A representative PRE-MIGRATION database. The migration chain is not replayable from zero (the historical
        // 20260603152331_AddItemCatalogSourceCompanyFix re-adds the columns 20260603151258 already added — SQL error 2705; see
        // docs/BACKLOG-MIGRATION-CHAIN-REPLAY.md — environments were never built by Migrate() from scratch; they apply idempotent
        // scripts generated by dotnet ef, see .github/workflows/apply-migrations-*.yml). So the schema
        // at the previous migration is built as: current model (EnsureCreated) minus the objects this migration adds, plus a
        // __EFMigrationsHistory that records every migration up to the previous one — exactly the state TEST/PROD are in today.
        await ctx.Database.EnsureCreatedAsync();
        await ctx.Database.ExecuteSqlRawAsync("DROP TABLE [PoDocumentExtractions]");
        await ctx.Database.ExecuteSqlRawAsync("ALTER TABLE [RequestPoGroups] DROP COLUMN [CurrentPoAttachmentId]");
        await ctx.Database.ExecuteSqlRawAsync("ALTER TABLE [RequestAttachments] DROP COLUMN [SupersededAtUtc], [SupersededByAttachmentId], [SupersededByUserId]");
        await ctx.Database.ExecuteSqlRawAsync("CREATE TABLE [__EFMigrationsHistory] ([MigrationId] nvarchar(150) NOT NULL, [ProductVersion] nvarchar(32) NOT NULL, CONSTRAINT [PK___EFMigrationsHistory] PRIMARY KEY ([MigrationId]))");
        var all = ctx.Database.GetMigrations().ToList();
        Assert.Equal(TargetMigration, all.Last());
        Assert.Equal(PreviousMigration, all[all.IndexOf(TargetMigration) - 1]);
        foreach (var m in all.TakeWhile(m => m != TargetMigration))
            await ctx.Database.ExecuteSqlRawAsync("INSERT INTO [__EFMigrationsHistory] ([MigrationId], [ProductVersion]) VALUES ({0}, '8.0.2')", m);
        int Scalar(string sql) => ctx.Database.SqlQueryRaw<int>(sql).AsEnumerable().First();
        Assert.Equal(0, Scalar("SELECT CAST(ISNULL(COL_LENGTH('dbo.RequestPoGroups','CurrentPoAttachmentId'),0) AS int) AS [Value]"));
        Assert.Equal(0, Scalar("SELECT CAST(ISNULL(COL_LENGTH('dbo.RequestAttachments','SupersededAtUtc'),0) AS int) AS [Value]"));
        Assert.Equal(0, Scalar("SELECT CAST(ISNULL(OBJECT_ID('dbo.PoDocumentExtractions'),0) AS int) AS [Value]"));
        Assert.Equal(1, Scalar($"SELECT COUNT(*) AS [Value] FROM __EFMigrationsHistory WHERE MigrationId = '{PreviousMigration}'"));
        Assert.Equal(0, Scalar($"SELECT COUNT(*) AS [Value] FROM __EFMigrationsHistory WHERE MigrationId = '{TargetMigration}'"));

        // Pre-migration rows (no new columns exist yet). Only the columns this rehearsal cares about are meaningful; every other NOT
        // NULL column without a default receives a type-appropriate placeholder, and FK checks are disabled on this disposable database.
        var requestId = Guid.NewGuid(); var groupA = Guid.NewGuid(); var groupB = Guid.NewGuid(); var cancelledGroup = Guid.NewGuid();
        var fileOld = Guid.NewGuid(); var fileNew = Guid.NewGuid(); var fileVoided = Guid.NewGuid(); var fileOtherGroup = Guid.NewGuid(); var fileCancelled = Guid.NewGuid();
        await ctx.Database.ExecuteSqlRawAsync("EXEC sp_MSforeachtable 'ALTER TABLE ? NOCHECK CONSTRAINT ALL'");
        await InsertAsync(ctx, "RequestPoGroups", new Dictionary<string, object?> { ["Id"] = groupA, ["RequestId"] = requestId, ["Status"] = "WAITING_PO_CORRECTION", ["PurchaseOrderNumber"] = "TEST-MAQSIS-2026-9003", ["TotalAmount"] = 230000m, ["CurrencyCode"] = "AOA", ["CreatedAtUtc"] = DateTime.UtcNow.AddDays(-3), ["CreatedByUserId"] = Guid.NewGuid() });
        await InsertAsync(ctx, "RequestPoGroups", new Dictionary<string, object?> { ["Id"] = groupB, ["RequestId"] = requestId, ["Status"] = "PO_ISSUED", ["PurchaseOrderNumber"] = "ECF99 2026/9002", ["TotalAmount"] = 120000m, ["CurrencyCode"] = "AOA", ["CreatedAtUtc"] = DateTime.UtcNow.AddDays(-3), ["CreatedByUserId"] = Guid.NewGuid() });
        await InsertAsync(ctx, "RequestPoGroups", new Dictionary<string, object?> { ["Id"] = cancelledGroup, ["RequestId"] = requestId, ["Status"] = "CANCELLED", ["PurchaseOrderNumber"] = "ECF99 2026/9001", ["TotalAmount"] = 250000m, ["CurrencyCode"] = "AOA", ["CreatedAtUtc"] = DateTime.UtcNow.AddDays(-3), ["CreatedByUserId"] = Guid.NewGuid() });
        var t0 = DateTime.UtcNow.AddHours(-3);
        await InsertAsync(ctx, "RequestAttachments", Att(fileOld, requestId, groupA, "Cotacao_TEST_MAQSIS_9003_REQ628.pdf", t0));
        await InsertAsync(ctx, "RequestAttachments", Att(fileNew, requestId, groupA, "PO_Ficticia_MAQSIS_9003_REQ628.pdf", t0.AddHours(1)));
        await InsertAsync(ctx, "RequestAttachments", Att(fileVoided, requestId, groupA, "po-voided.pdf", t0.AddHours(2), voided: true));
        await InsertAsync(ctx, "RequestAttachments", Att(fileOtherGroup, requestId, groupB, "po-b.pdf", t0.AddHours(2)));
        await InsertAsync(ctx, "RequestAttachments", Att(fileCancelled, requestId, cancelledGroup, "po-cancelled.pdf", t0, voided: true));

        // Apply the REAL migration the way the workflows do: the idempotent SQL dotnet ef generates for previous → target.
        var migrator = ctx.GetService<IMigrator>();
        var script = migrator.GenerateScript(PreviousMigration, TargetMigration, MigrationsSqlGenerationOptions.Idempotent);
        Assert.DoesNotContain("DROP ", script.ToUpperInvariant());   // no destructive statement in the forward script
        async Task RunScriptAsync()
        {
            // One session for every GO batch (the script opens BEGIN TRANSACTION in one batch and COMMITs in a later one), as
            // sqlcmd would run it; the outer EF transaction only keeps the connection and nests the script's own transaction.
            await using var session = await ctx.Database.BeginTransactionAsync();
            foreach (var batch in script.Split(new[] { "\r\nGO", "\nGO" }, StringSplitOptions.RemoveEmptyEntries).Select(b => b.Trim()).Where(b => b.Length > 0 && b != "GO"))
                await ctx.Database.ExecuteSqlRawAsync(batch);
            await session.CommitAsync();
        }
        await RunScriptAsync();

        Assert.Equal(1, Scalar("SELECT CAST(CASE WHEN COL_LENGTH('dbo.RequestPoGroups','CurrentPoAttachmentId') IS NULL THEN 0 ELSE 1 END AS int) AS [Value]"));
        Assert.Equal(1, Scalar("SELECT CAST(CASE WHEN OBJECT_ID('dbo.PoDocumentExtractions') IS NULL THEN 0 ELSE 1 END AS int) AS [Value]"));
        Assert.Equal(1, Scalar($"SELECT COUNT(*) AS [Value] FROM __EFMigrationsHistory WHERE MigrationId = '{TargetMigration}'"));
        // Legacy rows untouched: new columns NULL, nothing deleted, nothing voided by the migration.
        Assert.Equal(3, Scalar("SELECT COUNT(*) AS [Value] FROM RequestPoGroups WHERE CurrentPoAttachmentId IS NULL"));
        Assert.Equal(5, Scalar("SELECT COUNT(*) AS [Value] FROM RequestAttachments WHERE SupersededAtUtc IS NULL AND SupersededByAttachmentId IS NULL AND SupersededByUserId IS NULL"));
        Assert.Equal(2, Scalar("SELECT COUNT(*) AS [Value] FROM RequestAttachments WHERE VoidedAtUtc IS NOT NULL"));
        Assert.Equal("TEST-MAQSIS-2026-9003", ctx.Database.SqlQueryRaw<string>("SELECT PurchaseOrderNumber AS [Value] FROM RequestPoGroups WHERE Id = {0}", groupA).AsEnumerable().Single());
        // Idempotent: applying the same script again changes nothing and fails nothing.
        await RunScriptAsync();
        Assert.Equal(1, Scalar($"SELECT COUNT(*) AS [Value] FROM __EFMigrationsHistory WHERE MigrationId = '{TargetMigration}'"));

        // Read through the migrated model with the shared reader rule.
        await using var reader = NewCtx();
        var attachments = await reader.RequestAttachments.AsNoTracking().Where(a => a.RequestId == requestId).ToListAsync();
        var candidates = attachments.Select(a => new PoDocumentSelection.Candidate(a.Id, a.RequestPoGroupId, a.AttachmentTypeCode, a.UploadedAtUtc, a.IsDeleted, a.VoidedAtUtc, a.SupersededAtUtc)).ToList();
        var groups = await reader.RequestPoGroups.AsNoTracking().Where(g => g.RequestId == requestId).ToDictionaryAsync(g => g.Id);
        Assert.Null(groups[groupA].CurrentPoAttachmentId);
        Assert.Equal(fileNew, PoDocumentSelection.ResolveCurrentPoAttachmentId(groupA, groups[groupA].CurrentPoAttachmentId, candidates));   // newest LIVE file (the voided newer one is skipped)
        Assert.Equal(fileOtherGroup, PoDocumentSelection.ResolveCurrentPoAttachmentId(groupB, groups[groupB].CurrentPoAttachmentId, candidates)); // never across groups
        Assert.Null(PoDocumentSelection.ResolveCurrentPoAttachmentId(cancelledGroup, groups[cancelledGroup].CurrentPoAttachmentId, candidates)); // cancelled: files voided → no current document
        Assert.Equal(0, await reader.PoDocumentExtractions.CountAsync());

        await ctx.Database.EnsureDeletedAsync();
    }

    private static Dictionary<string, object?> Att(Guid id, Guid requestId, Guid groupId, string name, DateTime uploadedAt, bool voided = false) => new()
    {
        ["Id"] = id, ["RequestId"] = requestId, ["RequestPoGroupId"] = groupId, ["FileName"] = name, ["FileExtension"] = ".pdf", ["AttachmentTypeCode"] = "PO",
        ["StorageReference"] = name, ["UploadedByUserId"] = Guid.NewGuid(), ["UploadedAtUtc"] = uploadedAt, ["IsDeleted"] = false, ["FileSizeMBytes"] = 0.1m,
        ["VoidedAtUtc"] = voided ? uploadedAt.AddMinutes(1) : null, ["VoidReason"] = voided ? "ZZTEST anulado" : null,
    };

    /// <summary>Inserts a row with the explicit values plus type-appropriate placeholders for every other NOT NULL column without a default.</summary>
    private static async Task InsertAsync(ApplicationDbContext ctx, string table, Dictionary<string, object?> values)
    {
        var required = ctx.Database.SqlQueryRaw<string>(
            $"SELECT COLUMN_NAME + '|' + DATA_TYPE AS [Value] FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME = '{table}' AND IS_NULLABLE = 'NO' AND COLUMN_DEFAULT IS NULL " +
            "AND COLUMNPROPERTY(OBJECT_ID(TABLE_SCHEMA + '.' + TABLE_NAME), COLUMN_NAME, 'IsIdentity') = 0 AND COLUMNPROPERTY(OBJECT_ID(TABLE_SCHEMA + '.' + TABLE_NAME), COLUMN_NAME, 'IsComputed') = 0")
            .AsEnumerable().Select(x => x.Split('|')).ToList();
        var all = new Dictionary<string, object?>(values, StringComparer.OrdinalIgnoreCase);
        foreach (var (col, type) in required.Select(r => (r[0], r[1])))
        {
            if (all.ContainsKey(col)) continue;
            all[col] = type switch
            {
                "uniqueidentifier" => Guid.NewGuid(),
                "bit" => false,
                "int" or "bigint" or "smallint" or "tinyint" => 1,
                "decimal" or "numeric" or "money" or "float" or "real" => 0m,
                "datetime2" or "datetime" or "date" or "datetimeoffset" => DateTime.UtcNow,
                "timestamp" or "rowversion" => null,   // generated by SQL Server
                _ => "ZZTEST",
            };
            if (all[col] == null) all.Remove(col);
        }
        var cols = all.Keys.ToList();
        var parameters = cols.Select((c, i) => new SqlParameter("@p" + i, all[c] ?? DBNull.Value)).ToArray();
        var sql = $"INSERT INTO [{table}] ({string.Join(", ", cols.Select(c => "[" + c + "]"))}) VALUES ({string.Join(", ", cols.Select((_, i) => "@p" + i))})";
        await ctx.Database.ExecuteSqlRawAsync(sql, parameters);
    }
}

