interface EmployeeOption {
    id: string;
    fullName: string;
    employeeCode: string;
    innuxEmployeeId: number;
    innuxDepartmentName: string | null;
}

function EmployeeAutocomplete({ value, onChange }: {
    value: EmployeeOption | null;
    onChange: (emp: EmployeeOption | null) => void;
}) {
    const [query, setQuery] = useState('');
    const [options, setOptions] = useState<EmployeeOption[]>([]);
    const [showDropdown, setShowDropdown] = useState(false);
    const [searching, setSearching] = useState(false);
    const [activeIndex, setActiveIndex] = useState(-1);
    const debounceRef = useRef<ReturnType<typeof setTimeout> | null>(null);
    const wrapperRef = useRef<HTMLDivElement>(null);
    const inputRef = useRef<HTMLInputElement>(null);

    // Debounced search
    useEffect(() => {
        if (value) return; // Don't search when an employee is already selected
        if (query.trim().length < 2) {
            setOptions([]);
            setShowDropdown(false);
            return;
        }
        setSearching(true);
        if (debounceRef.current) clearTimeout(debounceRef.current);
        debounceRef.current = setTimeout(async () => {
            try {
                const res = await api.hrLeave.getEmployees({ search: query.trim(), pageSize: 15 });
                const items: EmployeeOption[] = (res.items || []).filter((e: any) => e.innuxEmployeeId > 0);
                setOptions(items);
                setShowDropdown(true);
                setActiveIndex(-1);
            } catch {
                setOptions([]);
            } finally {
                setSearching(false);
            }
        }, 300);
        return () => { if (debounceRef.current) clearTimeout(debounceRef.current); };
    }, [query, value]);

    // Close dropdown on outside click
    useEffect(() => {
        const handler = (e: MouseEvent) => {
            if (wrapperRef.current && !wrapperRef.current.contains(e.target as Node)) {
                setShowDropdown(false);
            }
        };
        document.addEventListener('mousedown', handler);
        return () => document.removeEventListener('mousedown', handler);
    }, []);

    const selectEmployee = (emp: EmployeeOption) => {
        onChange(emp);
        setQuery('');
        setShowDropdown(false);
        setOptions([]);
    };

    const clearSelection = () => {
        onChange(null);
        setQuery('');
        setOptions([]);
        setShowDropdown(false);
        inputRef.current?.focus();
    };

    const handleKeyDown = (e: React.KeyboardEvent) => {
        if (!showDropdown || options.length === 0) return;
        if (e.key === 'ArrowDown') {
            e.preventDefault();
            setActiveIndex(i => Math.min(i + 1, options.length - 1));
        } else if (e.key === 'ArrowUp') {
            e.preventDefault();
            setActiveIndex(i => Math.max(i - 1, 0));
        } else if (e.key === 'Enter' && activeIndex >= 0) {
            e.preventDefault();
            selectEmployee(options[activeIndex]);
        } else if (e.key === 'Escape') {
            setShowDropdown(false);
        }
    };

    return (
        <div className="diag-employee-autocomplete" ref={wrapperRef}>
            {value ? (
                <>
                    <input
                        type="text"
                        readOnly
                        value={`${value.fullName} (#${value.innuxEmployeeId})`}
                        style={{ cursor: 'default', fontWeight: 600 }}
                        onClick={() => inputRef.current?.focus()}
                    />
                    <button className="diag-employee-clear" onClick={clearSelection} title="Limpar seleção" type="button">
                        <X size={12} />
                    </button>
                </>
            ) : (
                <>
                    <input
                        ref={inputRef}
                        type="text"
                        placeholder="Pesquisar por nome do funcionário..."
                        value={query}
                        onChange={e => setQuery(e.target.value)}
                        onFocus={() => { if (options.length > 0) setShowDropdown(true); }}
                        onKeyDown={handleKeyDown}
                        autoComplete="off"
                    />
                    {searching && (
                        <span className="diag-employee-clear" style={{ background: 'transparent', cursor: 'default' }}>
                            <Loader2 size={12} />
                        </span>
                    )}
                </>
            )}
            {showDropdown && !value && (
                <div className="diag-employee-dropdown">
                    {searching ? (
                        <div className="diag-employee-loading">
                            <Loader2 size={14} /> A pesquisar...
                        </div>
                    ) : options.length === 0 ? (
                        <div className="diag-employee-no-results">
                            Nenhum funcionário encontrado.
                        </div>
                    ) : (
                        options.map((emp, i) => (
                            <div
                                key={emp.id}
                                className={`diag-employee-option ${i === activeIndex ? 'active' : ''}`}
                                onMouseDown={() => selectEmployee(emp)}
                                onMouseEnter={() => setActiveIndex(i)}
                            >
                                <span className="emp-name">{emp.fullName}</span>
                                <span className="emp-meta">
                                    {emp.innuxDepartmentName && <span>{emp.innuxDepartmentName}</span>}
                                    <span className="emp-id">ID #{emp.innuxEmployeeId}</span>
                                </span>
                            </div>
                        ))
                    )}
                </div>
            )}
        </div>
    );
}

